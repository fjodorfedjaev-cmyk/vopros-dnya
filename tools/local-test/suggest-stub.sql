create table public.questions (id integer generated by default as identity primary key, category text not null, text text not null, position integer not null, active boolean not null default false);
create table public.fill_prompts (id integer generated by default as identity primary key, text text not null, position integer not null, active boolean not null default false);
create table public.poll_questions (id serial primary key, text text not null, options jsonb not null, position integer not null default 0, active boolean not null default true, extra_from date);
create table public.daily_questions (day date primary key, question_id integer not null);
create table public.daily_fills (day date primary key, prompt_id integer not null);
create table public.daily_polls (day date primary key, poll_id integer not null);
create table public.daily_poll_extras (day date not null, slot smallint not null, poll_id integer not null, primary key (day, slot));
create table public.poll_extra_votes (user_id uuid not null, day date not null, slot smallint not null, choice smallint not null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), primary key (user_id, day, slot));
drop table if exists public.suggestions;
create table public.suggestions (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  kind text not null check (kind in ('question', 'fill', 'poll')),
  text text not null check (char_length(text) between 1 and 300),
  options jsonb check (options is null or jsonb_typeof(options) = 'array'),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  target_id integer
);

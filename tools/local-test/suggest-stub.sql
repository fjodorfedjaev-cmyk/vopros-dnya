create or replace function public.ensure_today_question()
returns table (q_day date, q_id integer, q_category text, q_text text)
language plpgsql security definer set search_path to 'public'
as $function$
declare d date := public.today_tallinn(); qid integer;
begin
  if not public.is_member() then raise exception 'not_member'; end if;
  select dq.question_id into qid from public.daily_questions dq where dq.day = d;
  if qid is null then
    select qs.id into qid from public.questions qs where qs.active
    order by (select max(dq.day) from public.daily_questions dq where dq.question_id = qs.id) asc nulls first, qs.position asc limit 1;
    insert into public.daily_questions (day, question_id) values (d, qid);
  end if;
  return query select d, qs.id, qs.category, qs.text from public.questions qs where qs.id = qid;
end $function$;
create or replace function public.ensure_today_fill()
returns table (q_day date, q_id integer, q_category text, q_text text)
language plpgsql security definer set search_path to 'public'
as $function$
declare d date := public.today_tallinn(); pid integer;
begin
  if not public.is_member() then raise exception 'not_member'; end if;
  select df.prompt_id into pid from public.daily_fills df where df.day = d;
  if pid is null then
    select fp.id into pid from public.fill_prompts fp where fp.active
    order by (select max(df.day) from public.daily_fills df where df.prompt_id = fp.id) asc nulls first, fp.position asc limit 1;
    insert into public.daily_fills (day, prompt_id) values (d, pid);
  end if;
  return query select d, fp.id, null::text, fp.text from public.fill_prompts fp where fp.id = pid;
end $function$;
